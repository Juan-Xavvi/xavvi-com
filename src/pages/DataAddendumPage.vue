					<li>Clause 7 (docking clause) applies;</li>
					<li>Clause 9, Option 2 (general written authorization) applies, with the notice period in Section 4.3;</li>
					<li>the optional wording in Clause 11 (independent dispute resolution body) does not apply;</li>
					<li>Clause 13: the supervisory authority is the one named in Clause 13(a) for Agency;</li>
					<li>Clauses 17 and 18: Irish law governs, and disputes go to the courts of Ireland; and</li>
					<li>Annexes I and II of the SCCs are completed by Annexes 1 and 2 of this DPA.</li>
				</ul>
				<p><strong>7.3 UK transfers.</strong> Where Agency Personal Data subject to the UK GDPR is transferred to a country without UK adequacy regulations, the UK Addendum applies, completed with the details in Section 7.2 and Annexes 1 to 3. Either party may end the UK Addendum as allowed by its Section 19.</p>
				<p><strong>7.4 Swiss transfers.</strong> Where the Swiss Federal Act on Data Protection applies, the SCCs apply as in Section 7.2, with the Swiss Federal Data Protection and Information Commissioner as supervisory authority and references to member states read to include Switzerland.</p>
				<p><strong>7.5 Onward transfers to AI Centers and Model Providers.</strong> Before any sub-processor outside the EU, UK or an adequate country processes Agency Personal Data, Xavvi will put in place SCCs (Module 3), the UK Addendum or another valid transfer mechanism with that sub-processor. Xavvi will carry out and keep a transfer impact assessment for each country where AI Centers or Model Providers are located, and will share a summary with Agency on request.</p>
				<p><strong>7.6 Other mechanisms.</strong> If Xavvi certifies under the EU-US Data Privacy Framework or its UK extension, or another valid mechanism becomes available, Xavvi may rely on it instead, and will tell Agency.</p>

