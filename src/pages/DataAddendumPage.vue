				<h2>1. Scope, roles and order of precedence</h2>
				<p><strong>1.1 Roles.</strong> For Agency Personal Data, Agency is the controller (or, where Agency acts for an End Client, a processor acting on the End Client's instructions) and Xavvi is a processor. Under US State Privacy Laws, Agency is the business and Xavvi is a service provider or contractor. AI Centers and Model Providers are Xavvi's sub-processors.</p>
				<p><strong>1.2 Xavvi as controller.</strong> Xavvi is an independent controller only for personal data it needs to run its own business, such as account, billing, security and fraud-prevention data about Agency's users. This DPA does not apply to that data, which Xavvi handles under its privacy policy.</p>
				<p><strong>1.3 Order of precedence.</strong> If this DPA conflicts with the Agreement, this DPA controls for Personal Data. If the Standard Contractual Clauses or UK Addendum conflict with this DPA, they control.</p>
				<p><strong>1.4 Agency's instructions.</strong> The Agreement, this DPA and Agency's use of the Platform are Agency's complete instructions to Xavvi. Agency is responsible for having a lawful basis, and any notices and consents required, for the Personal Data it uploads, including consent from any person whose face, voice or likeness appears in a Brief.</p>

