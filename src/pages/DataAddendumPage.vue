				<h2>4. Sub-processors</h2>
				<p><strong>4.1 General authorization.</strong> Agency authorizes Xavvi to engage the categories of sub-processors in Annex 3. Xavvi keeps a current list of its named sub-processors (other than AI Centers) on the Platform.</p>
				<p><strong>4.2 AI Centers.</strong> For each Order, the AI Center that Agency selects becomes a sub-processor for that Order. Agency's selection of an AI Center is its approval of that AI Center as a sub-processor. The Platform shows the country where each AI Center is based before Agency selects it.</p>
				<p><strong>4.3 Changes.</strong> Xavvi will give Agency at least 30 days' notice, by email or on the Platform, before adding or replacing a sub-processor listed under Section 4.1. Agency may object on reasonable data protection grounds within that period. If the parties cannot resolve the objection, Agency may stop using the affected part of the Platform or terminate the Agreement, and Xavvi will refund any unused Videos at the price paid.</p>
				<p><strong>4.4 Sub-processor terms.</strong> Xavvi will put a written contract in place with each sub-processor that gives Personal Data at least the protection of this DPA, including the security and confidentiality terms. Each AI Center may access Personal Data only inside the Platform and only for its assigned Order, and may not download, copy or keep it.</p>
				<p><strong>4.5 Responsibility.</strong> Xavvi remains responsible to Agency for each sub-processor's performance of its data protection obligations.</p>

				<!-- 5 -->
				<h2>5. Security and personal data breaches</h2>
				<p><strong>5.1 Security.</strong> Xavvi will maintain technical and organizational measures appropriate to the risk, including those in Annex 2. Xavvi may update them, as long as the overall level of protection does not go down.</p>
				<p><strong>5.2 Breach notice.</strong> Xavvi will notify Agency without undue delay, and in any case within 48 hours, after becoming aware of a Personal Data Breach affecting Agency Personal Data. This lets Agency meet the 72-hour notice rule under the EU and UK GDPR. The notice will describe, as far as then known, the nature of the breach, the categories and approximate number of people and records affected, the likely consequences, and the steps taken or proposed. Xavvi will send further information as it becomes available.</p>
				<p><strong>5.3 Response.</strong> Xavvi will take reasonable steps to contain and fix the breach, and will help Agency with any notice it must give to regulators or affected people. Xavvi will not notify Agency's End Clients or affected people directly unless Agency agrees or the law requires it.</p>
				<p><strong>5.4 No admission.</strong> A notice under this Section is not an admission of fault.</p>

				<!-- 6 -->
				<h2>6. Assistance and audits</h2>
				<p><strong>6.1 Data subject requests.</strong> If Xavvi receives a request from a person exercising their privacy rights (such as access, correction, deletion, objection or portability) about Agency Personal Data, it will pass the request to Agency and will not respond itself, except to confirm it was passed on. Xavvi will help Agency respond, mainly through Platform tools that let Agency find, export and delete its data.</p>
				<p><strong>6.2 Impact assessments.</strong> Xavvi will give Agency reasonable help with data protection impact assessments and prior consultations with supervisory authorities, to the extent they relate to Xavvi's processing.</p>
				<p><strong>6.3 Authority requests.</strong> If a government or regulator asks Xavvi for Agency Personal Data, Xavvi will redirect it to Agency where possible, tell Agency promptly unless the law forbids it, and disclose only what it is legally required to.</p>
				<p><strong>6.4 Audits.</strong> Once a year, or after a Personal Data Breach, Agency may ask Xavvi for written information showing compliance with this DPA, including any security certifications or third-party audit reports Xavvi holds. If that is not enough to show compliance, or a supervisory authority requires it, Agency may audit Xavvi on at least 30 days' notice, during business hours, at Agency's cost, through an independent auditor bound by confidentiality. Audits may not reach other customers' data.</p>

