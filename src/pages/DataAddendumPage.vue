				<h2>2. Definitions</h2>
				<p>Capitalized terms not defined here have the meaning given in the Agreement.</p>
				<ul>
					<li><strong>Data Protection Laws</strong> — all laws on personal data that apply to the processing, including the EU GDPR, the UK GDPR, the UK Data Protection Act 2018, the Swiss Federal Act on Data Protection, and US State Privacy Laws.</li>
