				<h2>3. Xavvi's processing obligations</h2>
				<p>Xavvi will:</p>
				<ol class="alpha-list">
					<li>process Personal Data only on Agency's documented instructions under Section 1.4, including for transfers abroad, unless the law requires otherwise, in which case Xavvi will tell Agency first unless the law forbids it;</li>
					<li>tell Agency promptly if it believes an instruction breaks Data Protection Laws;</li>
					<li>use Personal Data only to provide the Platform and produce Agency's Videos, and never for its own purposes, for advertising, or to train AI models;</li>
					<li>ensure everyone authorized to process Personal Data, including AI Center staff, is bound by confidentiality;</li>
					<li>apply the security measures in Section 5 and Annex 2;</li>
					<li>engage sub-processors only under Section 4;</li>
					<li>help Agency meet its obligations under Section 6;</li>
					<li>delete or return Personal Data under Section 9; and</li>
					<li>give Agency the information reasonably needed to show compliance with this DPA, and allow audits under Section 6.4.</li>
				</ol>

