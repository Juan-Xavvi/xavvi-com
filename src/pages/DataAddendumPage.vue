				<p>This Data Processing Addendum (the "<strong>DPA</strong>") forms part of the Xavvi AI Video Pack Reseller Agreement (the "<strong>Agreement</strong>") between Xavvi Holdings, Inc. ("<strong>Xavvi</strong>") and the Agency named in the Agreement ("<strong>Agency</strong>"). It applies whenever Xavvi processes Personal Data on Agency's behalf to provide the Platform and produce Videos.</p>

