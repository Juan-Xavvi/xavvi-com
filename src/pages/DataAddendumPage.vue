				<p><strong>9.2 After the account ends.</strong> Within 90 days after Agency's account is closed and any period under Section 10.4 of the Agreement has ended, Xavvi will delete Agency Personal Data, or return it first if Agency asks before then. Xavvi may keep copies only where the law requires, and will keep them confidential and process them only for that purpose. Backups are overwritten in the normal backup cycle.</p>
				<p><strong>9.3 Liability.</strong> Each party's liability under this DPA is subject to the limits and exclusions in the Agreement, except where Data Protection Laws or the SCCs do not allow them, including any liability to data subjects.</p>
				<p><strong>9.4 Term.</strong> This DPA lasts as long as Xavvi processes Agency Personal Data and ends automatically once Section 9.2 is complete.</p>
				<p><strong>9.5 Changes in law.</strong> If Data Protection Laws change, or a regulator issues new standard clauses, Xavvi may update this DPA on 30 days' notice to keep it compliant, as long as the update does not reduce the protection for Personal Data.</p>
				<p><strong>9.6 Governing law.</strong> This DPA follows the governing law and courts of the Agreement, except where the SCCs or the UK Addendum require otherwise.</p>

