					<li><strong>UK GDPR</strong> — the EU GDPR as it forms part of UK law.</li>
					<li><strong>US State Privacy Laws</strong> — the California Consumer Privacy Act as amended by the California Privacy Rights Act ("<strong>CCPA</strong>"), and similar comprehensive privacy laws of other US states.</li>
					<li><strong>Personal Data</strong> — any information relating to an identified or identifiable person (including "personal information" under the CCPA) that Agency or an End Client uploads to the Platform, or that Xavvi or an AI Center processes for Agency under the Agreement.</li>
					<li><strong>Processing, controller, processor, data subject and supervisory authority</strong> — as defined in the EU GDPR. <strong>Business, service provider, contractor, sell and share</strong> — as defined in the CCPA.</li>
					<li><strong>Sub-processor</strong> — any third party, including an AI Center or Model Provider, that Xavvi engages to process Personal Data.</li>
					<li><strong>Personal Data Breach</strong> — a breach of security leading to the accidental or unlawful destruction, loss, alteration, unauthorized disclosure of, or access to, Personal Data.</li>
					<li><strong>Standard Contractual Clauses</strong> or <strong>SCCs</strong> — the clauses approved by the European Commission in Decision (EU) 2021/914.</li>
					<li><strong>UK Addendum</strong> — the International Data Transfer Addendum to the SCCs issued by the UK Information Commissioner under section 119A of the UK Data Protection Act 2018.</li>
				</ul>

